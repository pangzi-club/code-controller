#if DEBUG
import Foundation

/// Sample folders and files for Xcode Previews, written under the temporary
/// directory so previews never depend on the developer's home folder.
@MainActor
enum PreviewFixtures {
    static let sampleFolder: URL = makeSampleFolder()

    private static func makeSampleFolder() -> URL {
        let fileManager = FileManager.default
        let folder = fileManager.temporaryDirectory
            .appendingPathComponent("CodeViewerPreviews", isDirectory: true)
            .appendingPathComponent("Design", isDirectory: true)
        try? fileManager.createDirectory(at: folder, withIntermediateDirectories: true)

        let files: [(name: String, contents: String)] = [
            ("readme.md", "# Preview folder\n\nGenerated by PreviewFixtures.\n"),
            ("notes.txt", "Sample notes for the file list preview.\n"),
        ]
        for file in files {
            let url = folder.appendingPathComponent(file.name)
            guard !fileManager.fileExists(atPath: url.path) else { continue }
            try? file.contents.write(to: url, atomically: true, encoding: .utf8)
        }

        let screenshots = folder.appendingPathComponent("Screenshots", isDirectory: true)
        try? fileManager.createDirectory(at: screenshots, withIntermediateDirectories: true)
        return folder
    }
}
#endif
